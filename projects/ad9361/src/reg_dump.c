void ad9361_dump_registers(struct ad9361_rf_phy *phy)
{
	size_t i;
	int32_t val;

	printf("# AD9361 register dump\n");
	for (i = 0; i < NO_OS_ARRAY_SIZE(ad9361_reg_names); i++) {
		val = ad9361_spi_read(phy->spi, ad9361_reg_names[i].addr);
		if (val < 0) {
			printf("REG %s 0x%03X <read error %ld>\n",
			       ad9361_reg_names[i].name,
			       ad9361_reg_names[i].addr,
			       (long)val);
			continue;
		}
		printf("REG %s 0x%03X 0x%02X\n",
		       ad9361_reg_names[i].name,
		       ad9361_reg_names[i].addr,
		       (unsigned)val);
	}
}
